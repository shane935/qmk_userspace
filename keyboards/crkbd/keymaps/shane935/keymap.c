// clang-format on

bool process_record_user(uint16_t keycode, keyrecord_t *record) {
    if (keycode == OS_SWAP && record->event.pressed) {
        if (get_highest_layer(default_layer_state) == _LINUX) {
            set_single_persistent_default_layer(_MAC);
        } else {
            set_single_persistent_default_layer(_LINUX);
        }
        return false;
    }
    return true;
}

#ifdef OLED_ENABLE
bool oled_task_user(void) {
    if (is_keyboard_master()) {
        oled_write_ln_P(PSTR("OS"), false);
        if (get_highest_layer(default_layer_state) == _LINUX) {
            oled_write_ln_P(PSTR("LINUX"), false);
        } else {
            oled_write_ln_P(PSTR("MAC"), false);
        }
        // _TMUX is toggled, so without this there is no way to tell it is on.
        oled_write_ln_P(layer_state_is(_TMUX) ? PSTR("TMUX") : PSTR(""), false);
        oled_write_ln_P(is_caps_word_on() ? PSTR("CAPS") : PSTR(""), false);
    }
    return false;
}
#endif
